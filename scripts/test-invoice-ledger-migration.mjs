import { spawnSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const suffix = randomBytes(6).toString('hex');
const containerName = `techmigos-invoice-ledger-test-${suffix}`;
const image = 'postgres:16-alpine';

function run(command, args, { input, allowFailure = false } = {}) {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: 'utf8',
    input,
    maxBuffer: 4 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  if (!allowFailure && result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} failed:\n${result.stderr || result.stdout}`);
  }
  return result;
}

function psql(sql, allowFailure = false) {
  return run('docker', [
    'exec', '-i', containerName,
    'psql', '-X', '-v', 'ON_ERROR_STOP=1', '-U', 'postgres', '-d', 'postgres',
  ], { input: sql, allowFailure });
}

async function waitForPostgres() {
  for (let attempt = 0; attempt < 30; attempt += 1) {
    const result = run('docker', [
      'exec', containerName, 'pg_isready', '-U', 'postgres', '-d', 'postgres',
    ], { allowFailure: true });
    if (result.status === 0) return;
    await new Promise((resolveWait) => setTimeout(resolveWait, 500));
  }
  throw new Error('Temporary PostgreSQL did not become ready within 15 seconds.');
}

async function migration(name) {
  return readFile(resolve(root, 'supabase/migrations', name), 'utf8');
}

let started = false;
try {
  run('docker', ['run', '--detach', '--rm', '--name', containerName,
    '--network', 'none',
    '--env', 'POSTGRES_HOST_AUTH_METHOD=trust',
    image]);
  started = true;
  await waitForPostgres();

  psql(`
    create role anon nologin;
    create role authenticated nologin;
    create table public.crm_invoices (
      id bigint primary key,
      invoice_date date,
      invoice_number text,
      service_title text,
      customer_name text,
      total_amount numeric,
      status text
    );
    create table public.crm_finances (
      id bigint generated by default as identity primary key,
      invoice_id bigint,
      transaction_date date,
      transaction_type text,
      reference_id text,
      title text,
      client text,
      project text,
      amount numeric,
      status text,
      notes text,
      source text
    );
  `);

  psql(await migration('20260906130000_sync_invoice_income_ledger.sql'));
  psql(`
    do $$
    begin
      begin
        insert into public.crm_invoices (
          id, invoice_date, invoice_number, service_title, customer_name, total_amount, status
        ) values (900001, current_date, 'BROKEN-TARGET', 'Regression probe', 'Isolated test', 10, 'sent');
      exception when others then
        if sqlerrm not ilike '%no unique or exclusion constraint matching the ON CONFLICT specification%' then
          raise;
        end if;
        return;
      end;
      raise exception 'Expected the legacy conflict target to fail against the partial unique index.';
    end;
    $$;
  `);

  psql(await migration('20260919140000_fix_invoice_ledger_conflict_target.sql'));
  psql(await migration('20260919150000_revoke_anon_invoice_ledger_trigger.sql'));
  psql(`
    do $$
    begin
      if has_function_privilege('anon', 'public.sync_invoice_income_ledger()', 'execute') then
        raise exception 'Anonymous role retained EXECUTE on the invoice ledger trigger function.';
      end if;
      if not has_function_privilege('authenticated', 'public.sync_invoice_income_ledger()', 'execute') then
        raise exception 'Authenticated role lost its invoice ledger trigger function grant.';
      end if;
    end;
    $$;
  `);
  psql(`
    insert into public.crm_invoices (
      id, invoice_date, invoice_number, service_title, customer_name, total_amount, status
    ) values (900002, current_date, 'FIXED-TARGET', 'Website delivery', 'Isolated test', 1250, 'sent');

    do $$
    declare
      entry public.crm_finances%rowtype;
      entry_count integer;
    begin
      select count(*) into entry_count from public.crm_finances where invoice_id = 900002;
      select * into entry from public.crm_finances where invoice_id = 900002;
      if entry_count <> 1 or entry.amount <> 1250 or entry.status <> 'pending' then
        raise exception 'New invoice did not create one pending ledger entry with the expected total.';
      end if;

      update public.crm_invoices set total_amount = 1500, status = 'paid' where id = 900002;
      select count(*) into entry_count from public.crm_finances where invoice_id = 900002;
      select * into entry from public.crm_finances where invoice_id = 900002;
      if entry_count <> 1 or entry.amount <> 1500 or entry.status <> 'received' then
        raise exception 'Paid invoice update did not update its existing ledger entry.';
      end if;

      update public.crm_invoices set status = 'cancelled' where id = 900002;
      select count(*) into entry_count from public.crm_finances where invoice_id = 900002;
      select * into entry from public.crm_finances where invoice_id = 900002;
      if entry_count <> 1 or entry.status <> 'cancelled' then
        raise exception 'Cancelled invoice did not retain exactly one cancelled ledger entry.';
      end if;
    end;
    $$;

    insert into public.crm_finances (transaction_date, transaction_type, title, amount, status, source)
    values (current_date, 'expense', 'Manual finance row', 15, 'paid', 'manual');
  `);

  process.stdout.write('Invoice ledger migration regression passed: legacy failure reproduced; fixed insert, paid update, cancellation, and manual finance row verified.\n');
} finally {
  if (started) {
    // The name is generated above for this run and is scoped to this isolated test container.
    run('docker', ['rm', '--force', containerName], { allowFailure: true });
  }
}
