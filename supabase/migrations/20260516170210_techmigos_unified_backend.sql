create extension if not exists pgcrypto with schema extensions;

create schema if not exists app_private;
revoke all on schema app_private from anon, authenticated, public;

do $$
begin
  if not exists (select 1 from pg_type where typname = 'admin_role') then
    create type public.admin_role as enum ('super_admin', 'admin', 'sales');
  end if;
  if not exists (select 1 from pg_type where typname = 'lead_status') then
    create type public.lead_status as enum ('new', 'in_progress', 'qualified', 'closed');
  end if;
  if not exists (select 1 from pg_type where typname = 'lead_priority') then
    create type public.lead_priority as enum ('low', 'medium', 'high');
  end if;
  if not exists (select 1 from pg_type where typname = 'lead_type') then
    create type public.lead_type as enum ('contact', 'newsletter', 'careers', 'demo');
  end if;
end $$;

create or replace function app_private.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table public.admin_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  email text not null unique,
  full_name text not null default '',
  role public.admin_role not null default 'sales',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint admin_profiles_email_lower check (email = lower(email)),
  constraint admin_profiles_username_nonempty check (length(trim(username)) > 0)
);

create trigger admin_profiles_set_updated_at
before update on public.admin_profiles
for each row execute function app_private.set_updated_at();

create or replace function app_private.current_admin_role()
returns public.admin_role
language sql
stable
security definer
set search_path = ''
as $$
  select p.role
  from public.admin_profiles p
  where p.user_id = auth.uid()
    and p.is_active = true
  limit 1
$$;

create or replace function app_private.current_admin_is_active()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_profiles p
    where p.user_id = auth.uid()
      and p.is_active = true
  )
$$;

create or replace function app_private.current_admin_has_role(allowed_roles public.admin_role[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(app_private.current_admin_role() = 'super_admin'::public.admin_role, false)
      or coalesce(app_private.current_admin_role() = any(allowed_roles), false)
$$;

grant usage on schema app_private to authenticated;
grant execute on function app_private.current_admin_role() to anon, authenticated;
grant execute on function app_private.current_admin_is_active() to anon, authenticated;
grant execute on function app_private.current_admin_has_role(public.admin_role[]) to anon, authenticated;

