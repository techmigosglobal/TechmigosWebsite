create or replace function app_private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_email text := lower(coalesce(new.email, ''));
begin
  if normalized_email = 'techmigos.global@gmail.com' then
    insert into public.admin_profiles (user_id, username, email, full_name, role, is_active)
    values (
      new.id,
      'techmigos-global',
      normalized_email,
      coalesce(new.raw_user_meta_data ->> 'full_name', 'Techmigos Global'),
      'super_admin',
      true
    )
    on conflict (user_id) do update
      set email = excluded.email,
          role = 'super_admin',
          is_active = true,
          updated_at = now();
  end if;

  return new;
end;
$$;

